def getCube(dimensions,location,orientation):
        # Function to transform cube dimensions and location into a form that plot_surface can plot
        phi = np.arange(1,10,2)*np.pi/4
        Phi, Theta = np.meshgrid(phi, phi)

        xBody = np.cos(Phi)*np.sin(Theta) * dimensions[0]
        yBody = np.sin(Phi)*np.sin(Theta) * dimensions[1]
        zBody = np.cos(Theta)/np.sqrt(2) * dimensions[2]

        bodyCoords = np.array([xBody,yBody,zBody])
        bodyCoordsNew = bodyCoords.reshape(3,-1)
        coords = np.matmul(orientation,bodyCoordsNew)
        coords = coords.reshape(3,5,5)
        location = np.array(location)
        coords = coords + location[:, np.newaxis, np.newaxis]

        x,y,z = coords

        return x,y,z